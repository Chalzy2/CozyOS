'use strict';

/**
 * server/live-relay/ldce-roster-bridge.js
 * CozyOS — Live Distribution — LDCE Roster Bridge
 * Milestone: R040 Phase 3 (continuation)
 *
 * REAL SCOPE DISCLOSURE
 *   session-authority.js's header and server/live-relay/README.md both
 *   disclosed the same honest boundary: SessionAuthority's roleResolver
 *   contract matches core/modules/communication/ldce-session-engine.js
 *   #getParticipant()'s real return shape field-for-field, but this
 *   Node signaling process cannot load a browser-oriented
 *   LDCESessionEngine instance directly (it needs Firebase, IdentityEngine,
 *   AuthorizationCoordinator, CozyConversation — real modules, designed
 *   for a browser runtime). That entry named the next concrete step:
 *   "wiring an in-process/RPC bridge to a live LDCESessionEngine
 *   instance." This file IS that bridge's server-side half.
 *
 *   COMPOSITION, NOT A SECOND ROSTER
 *   This file never invents participant data. It only mirrors, in this
 *   process, whatever a session's real, already-authenticated HOST
 *   connection reports — and that report is itself generated by the
 *   real LDCESessionEngine.listParticipants() read API on the host's
 *   own device (see the paired client file,
 *   core/modules/communication/ldce-roster-reporter.js). No role,
 *   language, or presence value is fabricated here.
 *
 *   TRUST BOUNDARY
 *   updateRoster() is designed to be called ONLY after the signaling
 *   server has independently verified (via the connection's own
 *   server-issued, signed token — never a client claim) that the
 *   reporting connection really is the session's authenticated host.
 *   This file does not re-verify that itself; it is not a public
 *   network-facing entry point, and re-stating an authorization check
 *   this deep would duplicate, not strengthen, the real check already
 *   performed once in live-distribution-signaling-server.js#_onRosterSync().
 *
 *   FAIL-CLOSED STALENESS
 *   A mirrored roster is only trusted for `maxAgeMs` after it was last
 *   reported. Past that (e.g. the host tab crashed without a clean
 *   disconnect, or simply hasn't reported yet this session), roleResolver()
 *   returns null — the same "not a recognized participant" result
 *   SessionAuthority already treats as a hard denial. This file never
 *   silently reuses indefinitely-old roster data to keep answering
 *   "yes."
 */

const DEFAULT_MAX_AGE_MS = 30_000;

class LdceRosterBridge {
    /**
     * @param {object} [opts]
     * @param {number} [opts.maxAgeMs] How long a reported roster snapshot remains trusted.
     */
    constructor(opts = {}) {
        this.maxAgeMs = opts.maxAgeMs || DEFAULT_MAX_AGE_MS;
        /** sessionId -> { hostSub, receivedAt, byUserId: Map(userId -> record) } */
        this._sessions = new Map();

        // Bound once so `roleResolver` can be handed directly to
        // `new SessionAuthority({ roleResolver: bridge.roleResolver })`
        // without the caller needing to `.bind(bridge)` themselves.
        this.roleResolver = this.roleResolver.bind(this);
    }

    /**
     * registerHost() — REAL, DISCLOSED BOOTSTRAP BOUNDARY.
     *
     * Genuine chicken-and-egg problem this file must not hand-wave: the
     * host needs a signed token to open the WebSocket connection it
     * would use to call updateRoster() via roster-sync — but before any
     * roster has ever been reported, roleResolver() returns null for
     * EVERY userId, including the host's own. Something has to seed
     * "this userId really is this session's host" the first time,
     * before any LDCE roster snapshot has been received.
     *
     * This is not solved here by trusting an unauthenticated client
     * claim. The same honest boundary session-authority.js already
     * documents for its HTTP token endpoint applies here too:
     * `registerHost(sessionId, hostUserId)` is meant to be called by
     * the platform's OWN already-authenticated session-creation path
     * (e.g. the real IdentityEngine-backed endpoint that lets a user
     * start a church live session in the first place) — never by this
     * WebSocket protocol itself, and never in response to any message
     * carrying a client-asserted role. Calling this from network input
     * would recreate exactly the "role from an untrusted client"
     * problem SessionAuthority exists to prevent.
     *
     * Idempotent and additive-only: never overwrites a roster that
     * already has real (post-connect, LDCE-reported) entries with a
     * smaller bootstrap-only one — it only seeds the host entry if that
     * session has no roster at all yet.
     */
    registerHost(sessionId, hostUserId, extra = {}) {
        if (!sessionId || !hostUserId) return { success: false, reason: 'sessionId and hostUserId are required.' };
        if (this._sessions.has(sessionId)) return { success: true, alreadySeeded: true };
        const byUserId = new Map([[hostUserId, {
            userId: hostUserId,
            role: 'host',
            language: typeof extra.language === 'string' ? extra.language : null,
            muted: false,
            cameraOn: !!extra.cameraOn,
            joinedAt: extra.joinedAt || Date.now(),
        }]]);
        this._sessions.set(sessionId, { hostSub: hostUserId, receivedAt: Date.now(), byUserId });
        return { success: true, alreadySeeded: false };
    }

    /**
     * updateRoster() — the ONLY way this mirror's data changes after bootstrap.
     * @param {string} sessionId
     * @param {string} hostSub  The reporting connection's server-verified identity (conn.sub), recorded for audit — never trusted as an authorization check by itself.
     * @param {Array<{userId:string, role:string, language?:string, muted?:boolean, cameraOn?:boolean, joinedAt?:string|number}>} participants  Real LDCESessionEngine.listParticipants() output.
     */
    updateRoster(sessionId, hostSub, participants) {
        if (!sessionId) return { success: false, reason: 'sessionId is required.' };
        if (!Array.isArray(participants)) return { success: false, reason: 'participants must be an array.' };

        const byUserId = new Map();
        for (const p of participants) {
            if (!p || typeof p.userId !== 'string' || typeof p.role !== 'string') continue; // skip malformed entries rather than fabricate defaults
            byUserId.set(p.userId, {
                userId: p.userId,
                role: p.role,
                language: typeof p.language === 'string' ? p.language : null,
                muted: !!p.muted,
                cameraOn: !!p.cameraOn,
                joinedAt: p.joinedAt || null,
            });
        }

        this._sessions.set(sessionId, { hostSub, receivedAt: Date.now(), byUserId });
        return { success: true, count: byUserId.size };
    }

    /** clearSession() — real cleanup when a session's host disconnects/ends, so a stale roster from a finished session is never silently reused for a NEW session that happens to reuse the same sessionId later. */
    clearSession(sessionId) {
        this._sessions.delete(sessionId);
    }

    /**
     * roleResolver(sessionId, userId) — the exact contract
     * SessionAuthority requires (matches LDCESessionEngine.getParticipant()'s
     * shape). Fails closed (returns null) on: unknown session, unreported
     * user, or a stale (older than maxAgeMs) roster snapshot.
     */
    roleResolver(sessionId, userId) {
        const entry = this._sessions.get(sessionId);
        if (!entry) return null;
        if (Date.now() - entry.receivedAt > this.maxAgeMs) return null;
        const record = entry.byUserId.get(userId);
        return record ? { ...record } : null;
    }

    /** isFresh() — diagnostic/health helper, not used for any authorization decision itself. */
    isFresh(sessionId) {
        const entry = this._sessions.get(sessionId);
        return !!entry && (Date.now() - entry.receivedAt <= this.maxAgeMs);
    }

    /** lastReportedAt() — diagnostic helper for /healthz-style reporting. */
    lastReportedAt(sessionId) {
        return this._sessions.get(sessionId)?.receivedAt || null;
    }
}

module.exports = { LdceRosterBridge };
